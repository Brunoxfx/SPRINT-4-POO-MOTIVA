DECLARE
    v_inicio NUMBER;
BEGIN
    SELECT NVL(MAX(ID_EQUIPE), 0) + 1 INTO v_inicio FROM TB_EQUIPE_MANUTENCAO;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_EQUIPE_MANUTENCAO START WITH ' || v_inicio
        || ' INCREMENT BY 1 NOCACHE';

    SELECT NVL(MAX(ID_TRECHO), 0) + 1 INTO v_inicio FROM TB_TRECHO_RODOVIA;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_TRECHO_RODOVIA START WITH ' || v_inicio
        || ' INCREMENT BY 1 NOCACHE';

    SELECT NVL(MAX(ID_INTERVENCAO), 0) + 1 INTO v_inicio FROM TB_INTERVENCAO_OPERACIONAL;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_INTERVENCAO_OPERACIONAL START WITH ' || v_inicio
        || ' INCREMENT BY 1 NOCACHE';

    SELECT NVL(MAX(ID_RELATORIO), 0) + 1 INTO v_inicio FROM TB_RELATORIO_PRIORIDADE;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_RELATORIO_PRIORIDADE START WITH ' || v_inicio
        || ' INCREMENT BY 1 NOCACHE';
END;
/

SELECT SEQUENCE_NAME, LAST_NUMBER
FROM USER_SEQUENCES
WHERE SEQUENCE_NAME LIKE 'SQ\_%' ESCAPE '\'
ORDER BY SEQUENCE_NAME;
